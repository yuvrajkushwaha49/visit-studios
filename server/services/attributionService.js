const db = require('../db');
const { getOrgLeadSettings } = require('./trackingLinkService');

/**
 * Resolves server-side attribution and initial assignment from a validated tracking link.
 * Never trusts client-supplied organization_id, sales_head_id, or associate_id.
 */
function resolveAttributionFromLink(link, submittedProjectId = null, submittedConfigId = null) {
  const organizationId = link.organization_id;
  const settings = getOrgLeadSettings(organizationId);

  // Resolve project strictly within the link's organization
  let resolvedProject = null;
  const targetProjectId = link.project_id || submittedProjectId || null;
  if (targetProjectId) {
    resolvedProject = db.get(
      "SELECT id, organization_id, developer_id, name, location FROM projects WHERE id = ? AND organization_id = ? AND status = 'active'",
      [targetProjectId, organizationId]
    );
    if (!resolvedProject) {
      throw Object.assign(new Error('Selected project is invalid or unavailable for this organization.'), { status: 400 });
    }
  } else {
    throw Object.assign(new Error('Please select a project.'), { status: 400 });
  }

  // Resolve apartment configuration strictly within the resolved project
  let resolvedConfig = null;
  if (submittedConfigId) {
    resolvedConfig = db.get(
      'SELECT id, project_id, name, super_built_up_area, carpet_area, price FROM project_configurations WHERE id = ? AND project_id = ?',
      [submittedConfigId, resolvedProject.id]
    );
  }

  // Original attribution is immutable and comes solely from the tracking link
  const originalLinkOwnerId = link.owner_associate_id || link.owner_sales_head_id || link.creator_user_id;
  let originalAssociateId = link.owner_associate_id || null;
  let originalSalesHeadId = link.owner_sales_head_id || null;

  if (originalAssociateId && !originalSalesHeadId) {
    const assoc = db.get('SELECT sales_head_id FROM users WHERE id = ?', [originalAssociateId]);
    originalSalesHeadId = assoc?.sales_head_id || null;
  }

  // Initial working assignment policy
  let assignedAssociateId = originalAssociateId;
  let assignedSalesHeadId = originalSalesHeadId;
  let assignmentPolicyReason = null;

  if (!assignedAssociateId) {
    if (assignedSalesHeadId) {
      // Link generated by Sales Head
      if (settings.sales_head_link_assignment_policy === 'round_robin') {
        const nextAssoc = pickRoundRobinAssociate(organizationId, assignedSalesHeadId);
        if (nextAssoc) {
          assignedAssociateId = nextAssoc.id;
          assignedSalesHeadId = nextAssoc.sales_head_id || assignedSalesHeadId;
          assignmentPolicyReason = 'Auto-assigned via team round-robin policy';
        }
      }
      // Default 'team_pool': assignedAssociateId stays null, assignedSalesHeadId = owner_sales_head_id
    } else {
      // Link generated by Admin / Super Admin
      if (settings.admin_link_assignment_policy === 'round_robin') {
        const nextAssoc = pickRoundRobinAssociate(organizationId, null);
        if (nextAssoc) {
          assignedAssociateId = nextAssoc.id;
          assignedSalesHeadId = nextAssoc.sales_head_id || null;
          assignmentPolicyReason = 'Auto-assigned via organization round-robin policy';
        }
      }
      // Default 'unassigned': both stay null until assigned by Admin
    }
  }

  return {
    organizationId,
    settings,
    project: resolvedProject,
    configuration: resolvedConfig,
    trackingLinkId: link.id,
    campaignId: link.campaign_id || null,
    enquirySource: link.campaign_name
      ? `${link.source_name || 'Enquiry Link'} (${link.campaign_name})`
      : (link.source_name || 'Enquiry Link'),
    originalLinkOwnerId,
    originalAssociateId,
    originalSalesHeadId,
    assignedAssociateId,
    assignedSalesHeadId,
    assignmentPolicyReason
  };
}

function pickRoundRobinAssociate(organizationId, salesHeadId = null) {
  let sql = `
    SELECT u.id, u.sales_head_id,
      (SELECT COUNT(*) FROM leads l WHERE l.assigned_associate_id = u.id) as lead_count,
      (SELECT MAX(l.created_at) FROM leads l WHERE l.assigned_associate_id = u.id) as last_assigned_at
    FROM users u
    WHERE u.organization_id = ? AND u.role = 'sales_associate' AND u.status = 'active'
  `;
  const params = [organizationId];
  if (salesHeadId) {
    sql += ' AND u.sales_head_id = ?';
    params.push(salesHeadId);
  }
  sql += ' ORDER BY lead_count ASC, COALESCE(last_assigned_at, \'1970-01-01\') ASC, u.created_at ASC LIMIT 1';
  return db.get(sql, params);
}

module.exports = {
  resolveAttributionFromLink,
  pickRoundRobinAssociate
};
